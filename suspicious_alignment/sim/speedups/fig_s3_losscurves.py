"""
fig_s3_losscurves.py -- S3: expected one-step loss change of the dominant-projected and of the
bulk-projected update as a function of the step size, exact versus approximate filters, at the
states of the EXACT filter's trajectory (data: results/shadow_summary.json, written by
exp_shadow.py + analyze_shadow.py).

For an update direction O (shape factor included) the loss change of the S-projected step is
exactly quadratic,   E[L(W - eta P^S O) - L(W)] = -eta a_S + eta^2 b_S / 2,
so the curve is fixed by the window averages (a_S, b_S); it crosses zero at eta_S^loss = 2 a_S / b_S.
Plotted: the loss change relative to the mean loss of the window, for S = D (solid) and S = B
(dashed); the vertical line is the learning rate actually used on the trajectory.
   early window = steps 0..100  (large initialisation: the high-alignment checkpoints)
   late  window = steps 1600..2400

Output: figs/s3_losscurves_{muon,ht}_{early,late}.png,
        results/s3_window_table.md  (position of the learning rate relative to the two thresholds
        for every filter, configuration and window)
Run:    python3 fig_s3_losscurves.py
"""
import json
import os

import numpy as np
import plotstyle
import matplotlib.pyplot as plt

import config as cfg

plotstyle.apply()
M_SHOW = 100
FAMS = {'muon': ['identity', 'exact', 'muon_ns5', 'ech_r4', 'ech_rk', 'ech_rk_fro'],
        'ht': ['identity', 'exact', 'ht_ns', 'ht_interval_cycle', 'ht_stream', 'ht_stream_rk']}
TABLE = {'muon': ['identity', 'exact', 'muon_ns5', 'ech_r1', 'ech_r4', 'ech_r16', 'ech_rk', 'ech_r1_ideal', 'ech_r4_ideal',
                  'ech_r16_ideal', 'ech_rk_ideal', 'ech_r4_pol', 'ech_rk_pol', 'ech_r4_fro', 'ech_rk_fro'],
         'ht': ['identity', 'exact', 'ht_ns', 'ht_interval_cycle', 'ht_avg', 'muon_ns5', 'ht_stream', 'ht_stream_rk',
                'ht_stream_r4']}


def status(c, lr):
    dD = -lr * c['aD'] + 0.5 * lr ** 2 * c['bD']
    dB = -lr * c['aB'] + 0.5 * lr ** 2 * c['bB']
    st = ('D+' if dD > 0 else 'D-') + ('B+' if dB > 0 else 'B-')
    return {'D-B-': 'both-', 'D+B+': 'both+'}.get(st, st)


def main():
    summ = json.load(open(os.path.join(cfg.RES, 'shadow_summary.json')))
    tuned = json.load(open(os.path.join(cfg.RES, 'tuned_lr.json')))['table']
    sigs = cfg.SIGMAS
    eta = np.geomspace(1e-5, 1e1, 600)
    for fam, names in FAMS.items():
        for win in ('early', 'late'):
            fig, axes = plt.subplots(1, len(sigs), figsize=(4.6 * len(sigs), 4.2), sharey=True)
            for a, s in zip(axes, sigs):
                key = f'{fam}_m{M_SHOW}_s{s}'
                if key not in summ:
                    continue
                e = summ[key][win]
                lr = tuned[f'm{M_SHOW}_s{s}'][fam]['lr']
                for li, nm in enumerate(names):
                    c = e['stats'][nm]
                    exact = nm == 'exact'
                    col = plotstyle.INK if exact else (plotstyle.MUTED if nm == 'identity' else plotstyle.PALETTE[li - 2])
                    for S, ls in (('D', '-'), ('B', '--')):
                        dl = (-eta * c['a' + S] + 0.5 * eta ** 2 * c['b' + S]) / e['meta']['loss']
                        a.plot(eta, dl, ls, color=col, lw=2.0 if exact else 1.3,
                               label=('exact filter' if exact else ('identity (SGD on the momentum)' if nm == 'identity' else nm)) if S == 'D' else None)
                a.axvline(lr, color=plotstyle.AXIS, lw=1)
                a.axhline(0.0, color=plotstyle.AXIS, lw=1)
                a.set_xscale('log')
                a.set_yscale('symlog', linthresh=1e-6)
                a.set_xlabel('step size eta')
                a.set_title(f'm = {M_SHOW}, sigma = {s:g}, theta = {e["meta"]["theta"]:.5f}')
                a.legend(loc='upper left')
            axes[0].set_ylabel('expected one-step loss change / loss')
            fig.suptitle(f'{fam} family, {win} window of the exact trajectory: dominant-projected (solid) and '
                         f'bulk-projected (dashed) update; vertical line = learning rate used', fontsize=10)
            fig.tight_layout()
            fig.savefig(os.path.join(cfg.FIG, f's3_losscurves_{fam}_{win}.png'), dpi=130)
            plt.close(fig)

    md = ['# Position of the learning rate relative to the projected-update loss thresholds',
          '(generated by fig_s3_losscurves.py from results/shadow_summary.json; states of the exact trajectory, 2 seeds)\n',
          'cell = etaD / etaB [status at the learning rate used]; `both-`: both projected updates decrease the loss;',
          '`D+B-`: Deng window (the dominant-projected update INCREASES the loss, the bulk-projected one decreases it);',
          '`D-B+`: reverse window; `both+`: both increase the loss.\n']
    for fam in ('muon', 'ht'):
        for win in ('early', 'late'):
            md.append(f'\n## {fam} family, {win} window\n')
            keys = [(m, s) for m in cfg.MS for s in sigs if f'{fam}_m{m}_s{s}' in summ]
            md.append('| filter | ' + ' | '.join(f'm={m}, s={s:g}' for m, s in keys) + ' |')
            md.append('|---|' + '---|' * len(keys))
            md.append('| (theta of the window) | ' + ' | '.join(f"{summ[f'{fam}_m{m}_s{s}'][win]['meta']['theta']:.4f}" for m, s in keys) + ' |')
            for nm in TABLE[fam]:
                cells = []
                for m, s in keys:
                    c = summ[f'{fam}_m{m}_s{s}'][win]['stats'][nm]
                    lr = tuned[f'm{m}_s{s}'][fam]['lr']
                    # identity = SGD on the momentum: its thresholds are in SGD units, no status
                    cells.append(f"{c['etaD']:.2g} / {c['etaB']:.2g}" + ('' if nm == 'identity' else f' [{status(c, lr)}]'))
                md.append(f'| {nm} | ' + ' | '.join(cells) + ' |')
    open(os.path.join(cfg.RES, 's3_window_table.md'), 'w').write('\n'.join(md) + '\n')
    print('written figs/s3_losscurves_*.png and results/s3_window_table.md')


if __name__ == '__main__':
    main()
