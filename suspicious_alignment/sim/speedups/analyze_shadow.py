"""
analyze_shadow.py -- tables and figures for exp_shadow.py (S1b fidelity along trajectories, S3a
projected-update thresholds along trajectories) and exp_s3_frozen.py (S3b / S1c frozen states).

Windows along the driver trajectory (T = 2400 steps, records every 5 steps):
   early = steps 0..100    (large initialisation: very high alignment, spiked momentum spectrum)
   late  = steps 1600..2400 (last third)
For each window, quantities are averaged over the window, then over the seeds (mean, half-range
of the 2 seeds).  Thresholds: eta_S^loss = 2 <a_S> / <b_S>, ratio = eta_D^loss / eta_B^loss
(ratio < 1: Deng's "suspicious" ordering -- the dominant-projected update becomes loss-increasing
at a smaller step size than the bulk-projected one).

Output: results/shadow_summary.json, results/shadow_tables.md, figs/shadow_*.png, figs/s3_*.png
Run:    python3 analyze_shadow.py
"""
import glob
import json
import os

import numpy as np
import plotstyle
import matplotlib.pyplot as plt

import config as cfg

plotstyle.apply()
WINDOWS = {'early': (0, 100), 'late': (1600, 2400)}


def load():
    data = {}
    for f in sorted(glob.glob(os.path.join(cfg.RES, 'shadow_*_m*_seed*.npz'))):
        z = np.load(f, allow_pickle=False)
        fam = os.path.basename(f).split('_')[1]
        data.setdefault((fam, int(z['m']), float(z['sigma'])), {})[int(z['seed'])] = {k: z[k] for k in z.files}
    return data


def window_stats(z, lo, hi):
    rec = int(z['rec_every'])
    i0, i1 = lo // rec, max(hi // rec, lo // rec + 1)
    names = [str(n) for n in z['names']]
    keys = [str(k) for k in z['keys']]
    out = {}
    for j, nm in enumerate(names):
        mean = np.nanmean(z['data'][j, i0:i1], axis=0)
        d = {k: float(mean[i]) for i, k in enumerate(keys)}
        out[nm] = d
    if 'ht_avg' in names:      # interval scheme: cycle average of 4 NS5 steps and 1 exact-HT step
        out['ht_interval_cycle'] = {k: 0.8 * out['muon_ns5'][k] + 0.2 * out['exact'][k] for k in ('aD', 'bD', 'aB', 'bB')}
    for nm, d in out.items():
        d['etaD'] = 2 * d['aD'] / d['bD']
        d['etaB'] = 2 * d['aB'] / d['bB']
        d['ratio'] = d['etaD'] / d['etaB']
        d['eta_full'] = 2 * (d['aD'] + d['aB']) / (d['bD'] + d['bB'])
    meta = dict(theta=float(np.nanmean(z['theta'][i0:i1])), loss=float(np.nanmean(z['loss'][i0:i1])),
                s1_over_fro=float(np.nanmean(z['svals'][i0:i1, 0] / np.linalg.norm(z['svals'][i0:i1], axis=1))),
                sk1_over_fro=float(np.nanmean(z['svals'][i0:i1, cfg.K] / np.linalg.norm(z['svals'][i0:i1], axis=1))),
                smin_over_fro=float(np.nanmean(z['svals'][i0:i1, -1] / np.linalg.norm(z['svals'][i0:i1], axis=1))))
    for k in z:
        if k.startswith('frame_err_') or k.startswith('tau_ratio_'):
            meta[k] = float(np.nanmean(z[k][i0:i1]))
    return out, meta


def agg(vals):
    v = np.array(vals, dtype=float)
    return float(np.nanmean(v)), float((np.nanmax(v) - np.nanmin(v)) / 2) if len(v) > 1 else 0.0


def main():
    data = load()
    summary = {}
    for key in sorted(data):
        fam, m, sigma = key
        entry = {}
        for wname, (lo, hi) in WINDOWS.items():
            per_seed = {seed: window_stats(z, lo, hi) for seed, z in data[key].items()}
            seeds = sorted(per_seed)
            names = list(per_seed[seeds[0]][0].keys())
            st = {}
            for nm in names:
                st[nm] = {}
                for q in per_seed[seeds[0]][0][nm]:
                    st[nm][q], st[nm][q + '_hr'] = agg([per_seed[s][0][nm][q] for s in seeds])
            meta = {q: agg([per_seed[s][1][q] for s in seeds])[0] for q in per_seed[seeds[0]][1]}
            entry[wname] = dict(stats=st, meta=meta)
        summary[f'{fam}_m{m}_s{sigma}'] = entry
    json.dump(summary, open(os.path.join(cfg.RES, 'shadow_summary.json'), 'w'), indent=1)

    # --------------------------------------------------------------- markdown tables
    md = ['# Shadow-protocol tables (generated by analyze_shadow.py)\n',
          'Every approximation is evaluated on the momentum matrices of the EXACT filter\'s trajectory.',
          'rel = relative Frobenius error vs the exact filter; off = off-diagonal energy in the exact singular basis;',
          't_head / t_bulk = mean transfer on singular directions 1..20 / 21..40; bulk_gain = ||P^B F|| / ||P^B F_exact||;',
          'bulk_cos = cosine between the bulk-subspace parts; dom = fraction of the output in the dominant Hessian subspace;',
          'gain = <F, F_exact>/||F_exact||^2 (effective step-size factor);',
          'etaD, etaB = loss thresholds of the dominant- / bulk-projected update (units of the learning rate); ratio = etaD/etaB.',
          'Values: mean over the window and the 2 seeds (half-range of the seeds in parentheses for rel and ratio).\n']
    for key in sorted(data):
        fam, m, sigma = key
        e = summary[f'{fam}_m{m}_s{sigma}']
        for wname in WINDOWS:
            meta = e[wname]['meta']
            md.append(f"\n## {fam} family, m = {m}, sigma = {sigma}, window = {wname} "
                      f"(theta = {meta['theta']:.6f}; s_1/||M||_F = {meta['s1_over_fro']:.3f}, "
                      f"s_k+1/||M||_F = {meta['sk1_over_fro']:.2e}, s_min/||M||_F = {meta['smin_over_fro']:.2e})\n")
            md.append('| filter | rel | off | gain | t_head | t_bulk | bulk_gain | bulk_cos | dom | etaD | etaB | ratio D/B | eta_full |')
            md.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
            for nm, d in e[wname]['stats'].items():
                if 'rel' in d:
                    md.append(f"| {nm} | {d['rel']:.3g} ({d['rel_hr']:.2g}) | {d['off']:.2g} | {d['gain']:.3g} | {d['t_head']:.3g} | {d['t_bulk']:.3g} | "
                              f"{d['bulk_gain']:.3g} | {d['bulk_cos']:.3f} | {d['dom_frac']:.3f} | {d['etaD']:.3g} | {d['etaB']:.3g} | "
                              f"{d['ratio']:.3g} ({d['ratio_hr']:.2g}) | {d['eta_full']:.3g} |")
                else:
                    md.append(f"| {nm} |  |  |  |  |  |  |  |  | {d['etaD']:.3g} | {d['etaB']:.3g} | {d['ratio']:.3g} ({d['ratio_hr']:.2g}) | {d['eta_full']:.3g} |")
            if fam == 'muon':
                md.append('\ntracked Echelon frames: ' + ', '.join(
                    f"r={r}: frame error {meta[f'frame_err_r{r}']:.2e}, tau/||T||_2 {meta[f'tau_ratio_r{r}']:.3f}"
                    for r in [1, 4, 16, cfg.K]))
    open(os.path.join(cfg.RES, 'shadow_tables.md'), 'w').write('\n'.join(md) + '\n')

    # --------------------------------------------------------------- figures
    ms = sorted({k[1] for k in data})
    sigs = sorted({k[2] for k in data})
    show = {'muon': ['muon_ns5', 'ech_r1', 'ech_r4', 'ech_r16', 'ech_rk', 'ech_rk_ideal', 'ech_r4_ideal', 'ech_rk_fro'],
            'ht': ['ht_ns', 'muon_ns5', 'ht_avg', 'ht_stream', 'ht_stream_rk', 'ht_stream_r4']}
    # (1) relative error and bulk gain along the trajectory (seed 0)
    for quantity, ylab, logy in [('rel', 'relative error vs exact filter', True), ('bulk_gain', 'bulk gain  ||P^B F|| / ||P^B F_exact||', True)]:
        for m in ms:
            fig, axes = plt.subplots(2, len(sigs), figsize=(4.4 * len(sigs), 6.4), sharex=True, squeeze=False)
            for ci, s in enumerate(sigs):
                for ri, fam in enumerate(['muon', 'ht']):
                    a = axes[ri, ci]
                    if (fam, m, s) not in data:
                        continue
                    z = data[(fam, m, s)][min(data[(fam, m, s)])]
                    names = [str(n) for n in z['names']]
                    keys = [str(k) for k in z['keys']]
                    x = np.arange(z['data'].shape[1]) * int(z['rec_every'])
                    qi = keys.index(quantity)
                    for li, nm in enumerate(show[fam]):
                        y = z['data'][names.index(nm), :, qi]
                        a.plot(x, np.clip(y, 1e-12, None), color=plotstyle.PALETTE[li], lw=1.2, label=nm)
                    if logy:
                        a.set_yscale('log')
                    if ri == 0:
                        a.set_title(f'm = {m}, sigma = {s:g}')
                    if ri == 1:
                        a.set_xlabel('step of the exact-filter trajectory')
                    if ci == 0:
                        a.set_ylabel(f'{fam} family: {ylab}', fontsize=8)
                    a.legend(ncol=2)
            fig.suptitle(f'{ylab}: approximations fed with the momentum matrices of the exact trajectory (seed 0)', fontsize=10)
            fig.tight_layout()
            fig.savefig(os.path.join(cfg.FIG, f'shadow_{quantity}_m{m}.png'), dpi=130)
            plt.close(fig)
    # (2) threshold ratio etaD/etaB per filter, late and early windows
    order = {'muon': ['identity', 'exact', 'muon_ns5', 'ech_r1', 'ech_r4', 'ech_r16', 'ech_rk', 'ech_r1_ideal', 'ech_r4_ideal', 'ech_r16_ideal', 'ech_rk_ideal', 'ech_r4_pol', 'ech_rk_pol', 'ech_r4_fro', 'ech_rk_fro'],
             'ht': ['identity', 'exact', 'ht_ns', 'ht_interval_cycle', 'ht_avg', 'muon_ns5', 'ht_stream', 'ht_stream_rk', 'ht_stream_r4']}
    for wname in WINDOWS:
        fig, axes = plt.subplots(2, len(sigs), figsize=(4.6 * len(sigs), 7.6), squeeze=False, sharey='row')
        for ci, s in enumerate(sigs):
            for ri, fam in enumerate(['muon', 'ht']):
                a = axes[ri, ci]
                for mi, m in enumerate(ms):
                    k = f'{fam}_m{m}_s{s}'
                    if k not in summary:
                        continue
                    st = summary[k][wname]['stats']
                    y = [abs(st[nm]['ratio']) for nm in order[fam]]
                    neg = [st[nm]['ratio'] < 0 for nm in order[fam]]
                    a.plot(range(len(y)), y, 'o', ms=5, color=plotstyle.PALETTE[mi], label=f'm = {m}')
                    for xi, (yy, ng) in enumerate(zip(y, neg)):
                        if ng:
                            a.plot([xi], [yy], 'x', ms=7, color=plotstyle.INK)
                a.axhline(1.0, color=plotstyle.INK, lw=1)
                a.set_yscale('log')
                a.set_xticks(range(len(order[fam])))
                a.set_xticklabels(order[fam], rotation=60, ha='right', fontsize=7)
                if ri == 0:
                    a.set_title(f'sigma = {s:g}')
                if ci == 0:
                    a.set_ylabel(f'{fam} family: eta_D^loss / eta_B^loss')
                a.legend()
        fig.suptitle(f'Projected-update thresholds along the exact trajectory, window = {wname} '
                     f'(below 1: dominant update unstable first, as for SGD; x = negative ratio)', fontsize=10)
        fig.tight_layout()
        fig.savefig(os.path.join(cfg.FIG, f's3_ratio_{wname}.png'), dpi=130)
        plt.close(fig)

    # --------------------------------------------------------------- frozen states
    fz = os.path.join(cfg.RES, 's3_frozen.json')
    if os.path.exists(fz):
        rows = json.load(open(fz))['rows']
        tab = {}
        for r in rows:
            for nm, d in r['res'].items():
                tab.setdefault((r['m'], r['sigma'], r['one_minus_theta'], nm), []).append(d)
        fsum = {}
        for (m, s, omt, nm), lst in tab.items():
            fsum[f'm{m}_s{s}_omt{omt:g}_{nm}'] = {q: agg([x[q] for x in lst if q in x])[0] for q in lst[0]}
            fsum[f'm{m}_s{s}_omt{omt:g}_{nm}']['ratio_hr'] = agg([x['ratio_D_over_B'] for x in lst])[1]
        json.dump(fsum, open(os.path.join(cfg.RES, 's3_frozen_summary.json'), 'w'), indent=1)
        omts = sorted({r['one_minus_theta'] for r in rows}, reverse=True)
        fms = sorted({r['m'] for r in rows})
        fsig = sorted({r['sigma'] for r in rows})
        md = ['# Frozen-state tables (generated by analyze_shadow.py from results/s3_frozen.json)\n',
              'State with prescribed alignment theta, rms gradient entry 1; mean of 2 seeds.',
              'etaB = loss threshold of the bulk-projected update; ratio = etaD/etaB; bulk_gain = ||P^B F||/||P^B F_exact||.\n']
        groups = {'Muon family': ['sgd_deng', 'sgd_mc', 'sgdm', 'muon_exact', 'muon_ns5', 'ech_r1', 'ech_r4', 'ech_r16', 'ech_rk',
                                  'ech_r1_ideal', 'ech_r4_ideal', 'ech_r16_ideal', 'ech_rk_ideal', 'ech_r4_pol', 'ech_rk_pol', 'ech_r4_fro', 'ech_rk_fro'],
                  'HTMuon family': ['ht_exact', 'ht_ns', 'ht_interval_cycle', 'ht_avg', 'ht_stream', 'ht_stream_rk', 'ht_stream_r4']}
        for m in fms:
            for s in fsig:
                for q, qname in [('ratio_D_over_B', 'ratio etaD/etaB'), ('etaB', 'etaB'), ('etaD', 'etaD'), ('bulk_gain', 'bulk_gain'), ('rel', 'rel error vs exact')]:
                    md.append(f'\n## m = {m}, sigma = {s}: {qname}\n')
                    md.append('| filter | ' + ' | '.join(f'1-theta={o:g}' for o in omts) + ' |')
                    md.append('|---|' + '---|' * len(omts))
                    for g, lst in groups.items():
                        for nm in lst:
                            vals = [fsum[f'm{m}_s{s}_omt{o:g}_{nm}'].get(q, float('nan')) for o in omts]
                            if all(np.isnan(v) for v in vals):
                                continue
                            md.append(f'| {nm} | ' + ' | '.join(f'{v:.3g}' for v in vals) + ' |')
        open(os.path.join(cfg.RES, 's3_frozen_tables.md'), 'w').write('\n'.join(md) + '\n')
        for q, ylab, fn in [('ratio_D_over_B', 'eta_D^loss / eta_B^loss', 's3_frozen_ratio'), ('etaB', 'eta_B^loss (bulk-projected update)', 's3_frozen_etaB'),
                            ('bulk_gain', 'bulk gain ||P^B F|| / ||P^B F_exact||', 's3_frozen_bulk_gain')]:
            fig, axes = plt.subplots(2, len(fsig), figsize=(4.5 * len(fsig), 7.0), squeeze=False, sharex=True)
            mm = fms[-1]
            sets = [['sgdm', 'muon_exact', 'muon_ns5', 'ech_r4', 'ech_r16', 'ech_rk', 'ech_rk_fro', 'ech_rk_pol'],
                    ['sgdm', 'ht_exact', 'ht_ns', 'ht_interval_cycle', 'ht_stream', 'ht_stream_rk', 'ht_stream_r4']]
            for ci, s in enumerate(fsig):
                for ri, lst in enumerate(sets):
                    a = axes[ri, ci]
                    for li, nm in enumerate(lst):
                        y = np.array([fsum[f'm{mm}_s{s}_omt{o:g}_{nm}'].get(q, np.nan) for o in omts], dtype=float)
                        if np.all(np.isnan(y)):
                            continue
                        exact = nm in ('muon_exact', 'ht_exact')
                        a.plot(omts, np.abs(y), 'o-', ms=4, lw=2.0 if exact else 1.3,
                               color=plotstyle.INK if exact else (plotstyle.MUTED if nm == 'sgdm' else plotstyle.PALETTE[li - 2 if li >= 2 else 0]),
                               ls='--' if nm == 'sgdm' else '-', label=nm)
                    a.set_xscale('log')
                    a.set_yscale('log')
                    if q == 'ratio_D_over_B':
                        a.axhline(1.0, color=plotstyle.AXIS, lw=1)
                    if ri == 0:
                        a.set_title(f'm = {mm}, noise sigma = {s:g} x rms gradient entry')
                    if ri == 1:
                        a.set_xlabel('1 - theta  (distance of the alignment from 1)')
                    if ci == 0:
                        a.set_ylabel(('Muon family: ' if ri == 0 else 'HTMuon family: ') + ylab, fontsize=8)
                    a.legend()
            fig.suptitle(f'Frozen high-alignment states: {ylab}', fontsize=10)
            fig.tight_layout()
            fig.savefig(os.path.join(cfg.FIG, f'{fn}.png'), dpi=130)
            plt.close(fig)
    print('done:', len(summary), 'trajectory configs')


if __name__ == '__main__':
    main()
