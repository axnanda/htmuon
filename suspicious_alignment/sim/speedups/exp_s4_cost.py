"""
exp_s4_cost.py -- S4: flop counts of the dominant matrix operations per optimizer step.

Flop model of echelon-lean/FastMuon/Cost.lean (a multiply-add counts as 2 flops; an a x b by b x c
product costs 2abc).  For a layer of shape rows x cols let s = min(rows, cols), l = max(rows, cols).

  NS5 Muon            nsCost s l 5 = 5 (4 s^2 l + 2 s^3)                              [Cost.lean]
  exact SVD           svdCost l s = 4 l s^2 + 8 s^3  (Golub-Reinsch count used in
                      FastMuon/MuonVsSVD.lean); a thin SVD with BOTH factors costs
                      14 l s^2 + 8 s^3 (Golub-Reinsch) or 6 l s^2 + 20 s^3 (R-SVD) in
                      Golub & Van Loan's table -- reported as "svd_gvl" (the smaller of the two)
  exact Muon / HTMuon SVD + one s x s by s x l product to form U f(S) V^T  (+ 2 s^2 l)
  HTMuon-NS           NS5 + Gram matrix G^T G (2 rows cols^2) + 4 square roots x 5 coupled
                      Newton-Schulz steps x 3 products of cols x cols matrices (120 cols^3)
                      + the final product (2 rows cols^2).  NOTE: the Gram matrix is cols x cols,
                      whatever the orientation (muon.py:96), so for a wide layer the cubic term is
                      in the LARGER dimension.
  HTMuon-interval(5)  (4 NS5 + 1 exact HTMuon) / 5
  HTMuon-stream(q)    G V, G^T(G V), G V_t, (U s^p) V_t^T: 4 products = 8 rows cols q;
                      thin Householder QR of a cols x q matrix with explicit Q: 4 cols q^2 - 4 q^3/3
  Echelon(r)          htCost s l r = 6 s l r + 6 (s + l) r^2 + 20 r^3 + 10 s l            [Cost.lean]
  Echelon(r)+polish   htCost + 4 s^2 l                                                    [Polish.lean]

Whether wall-clock time follows flops is an empirical, hardware-dependent question (matmuls run at
tensor-core peak in bf16, SVD/QR do not) -- see the docstring of MuonVsSVD.lean.

Output: results/s4_cost.json, results/s4_cost.md
Run:    python3 exp_s4_cost.py
"""
import json
import os

import config as cfg


def ns_cost(s, l, k=5):
    return k * (4 * s ** 2 * l + 2 * s ** 3)


def svd_cost(l, s):
    return 4 * l * s ** 2 + 8 * s ** 3


def svd_gvl(l, s):
    return min(14 * l * s ** 2 + 8 * s ** 3, 6 * l * s ** 2 + 20 * s ** 3)


def ht_cost(s, l, r):
    return 6 * s * l * r + 6 * (s + l) * r ** 2 + 20 * r ** 3 + 10 * s * l


def costs(rows, cols, k_dom):
    s, l = min(rows, cols), max(rows, cols)
    form = 2 * s * s * l
    c = {}
    c['muon_ns5'] = ns_cost(s, l)
    c['muon_exact / ht_exact (SVD, repo count)'] = svd_cost(l, s) + form
    c['muon_exact / ht_exact (SVD, GVL thin count)'] = svd_gvl(l, s) + form
    c['ht_ns'] = ns_cost(s, l) + 2 * rows * cols ** 2 + 4 * 5 * 3 * 2 * cols ** 3 + 2 * rows * cols ** 2
    c['ht_interval(5) (repo SVD count)'] = (4 * ns_cost(s, l) + svd_cost(l, s) + form) / 5
    c['ht_interval(5) (GVL SVD count)'] = (4 * ns_cost(s, l) + svd_gvl(l, s) + form) / 5
    for q, tag in [(min(rows, cols), 'full'), (k_dom, f'rank {k_dom}'), (16, 'rank 16'), (4, 'rank 4')]:
        q = min(q, rows, cols)
        c[f'ht_stream ({tag})'] = 8 * rows * cols * q + 4 * cols * q ** 2 - 4 * q ** 3 / 3
    for r in [1, 4, 16, k_dom]:
        r = min(r, s)
        c[f'echelon(r={r})'] = ht_cost(s, l, r)
        c[f'echelon(r={r}) + polish'] = ht_cost(s, l, r) + 4 * s * s * l
    return c


def main():
    layers = {'200x40 (this study, k=20)': (200, 40, 20),
              '4096x4096 (k=410)': (4096, 4096, 410),
              '4096x16384 (wide MLP, k=410)': (4096, 16384, 410),
              '16384x4096 (tall MLP, k=410)': (16384, 4096, 410)}
    out = {}
    md = ['# S4 flop counts per step (generated by exp_s4_cost.py)\n']
    for lname, (rows, cols, k) in layers.items():
        c = costs(rows, cols, k)
        ns = c['muon_ns5']
        svd = c['muon_exact / ht_exact (SVD, repo count)']
        out[lname] = {nm: dict(flops=float(v), speedup_vs_ns5=float(ns / v), speedup_vs_svd=float(svd / v))
                      for nm, v in c.items()}
        md.append(f'\n## {lname}\n')
        md.append('| variant | flops | speed-up vs NS5 Muon | speed-up vs exact SVD (repo count) |')
        md.append('|---|---|---|---|')
        for nm, v in c.items():
            md.append(f'| {nm} | {v:.3g} | {ns / v:.3g} | {svd / v:.3g} |')
    json.dump(out, open(os.path.join(cfg.RES, 's4_cost.json'), 'w'), indent=1)
    open(os.path.join(cfg.RES, 's4_cost.md'), 'w').write('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
